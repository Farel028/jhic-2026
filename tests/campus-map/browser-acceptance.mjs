/* Set PLAYWRIGHT_MODULE to an external playwright/index.mjs if not installed locally. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(path.resolve(process.env.PLAYWRIGHT_MODULE)).href : 'playwright');
const base = process.env.MAP_QA_URL || 'http://127.0.0.1:3100';
const out = process.env.MAP_QA_OUTPUT || path.resolve('artifacts/campus-map');
fs.mkdirSync(out, { recursive: true });
const checks = [];
const record = (name) => { checks.push(name); console.log('PASS:', name); };
(async () => {
  const browser = await chromium.launch({ channel: process.env.MAP_QA_BROWSER || 'msedge', headless: true, args: ['--enable-unsafe-swiftshader'] });
  try {
    const page = await browser.newPage({ viewport: { width: 1440, height: 1050 }, deviceScaleFactor: 1 });
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    assert.equal((await page.goto(base + '/peta-sekolah', { waitUntil: 'networkidle', timeout: 120000 })).status(), 200);
    const canvas = page.locator('[data-testid="school-map-canvas"] canvas');
    await canvas.waitFor();
    await page.waitForFunction(() => !document.querySelector('button')?.textContent?.includes('Menyiapkan'));
    const top = page.getByRole('button', { name: 'Tampak atas', exact: true });
    await top.waitFor();
    assert.equal(await top.isEnabled(), true);
    record('Route 200 and interactive WebGL initialized');
    const list = page.getByRole('list', { name: 'Daftar ruang dan area' });
    const total = await list.getByRole('button').count();
    assert.ok(total > 0); record('Accessible room directory available');
    await page.locator('#map-search').fill('  AULA ');
    assert.equal(await list.getByRole('button').count(), 5); // Includes adjacent garden + meeting room location.
    await page.locator('#map-category').selectOption('toilet');
    assert.equal(await list.getByRole('button').count(), 0);
    assert.ok(await page.getByText('Tidak ada ruang yang cocok.', { exact: false }).isVisible());
    await page.getByRole('button', { name: 'Hapus filter', exact: true }).click();
    assert.equal(await list.getByRole('button').count(), total);
    record('Search, combined filter, empty state, and clear filter');
    await page.locator('#map-category').selectOption('toilet');
    assert.equal(await list.getByRole('button').count(), 2);
    await list.getByRole('button').first().focus();
    await page.keyboard.press('Enter');
    assert.equal(await page.getByRole('heading', { name: 'Kamar mandi kiri', exact: true }).count(), 1);
    record('Keyboard room selection opens room details');
    await page.getByRole('button', { name: 'Hapus filter', exact: true }).click();
    await page.locator('#map-search').fill('R. 08');
    assert.equal(await list.getByRole('button').count(), 8);
    record('Repeated source R. 08 codes preserved as eight distinct rooms');
    await page.getByRole('button', { name: 'Hapus filter', exact: true }).click();
    await page.getByLabel('Atap', { exact: true }).uncheck();
    await top.click();
    const box = await canvas.boundingBox();
    const halfHeight = Math.max(595 / 2, 1333 / 2 / (box.width / box.height)) * 1.08;
    const x = box.x + box.width / 2 + (928.5 - 1333 / 2) * box.height / (2 * halfHeight);
    const y = box.y + box.height / 2 + (292 - 595 / 2) * box.height / (2 * halfHeight);
    await page.mouse.click(x, y);
    assert.equal(await page.getByRole('heading', { name: 'Ruang Guru', exact: true }).count(), 1);
    record('Real canvas raycast selects Ruang Guru in top view');
    await page.getByRole('button', { name: 'Tutup detail', exact: true }).click();
    await page.mouse.move(x, y); await page.mouse.down(); await page.mouse.move(x + 60, y + 35, { steps: 10 }); await page.mouse.up();
    assert.equal(await page.getByRole('button', { name: 'Tutup detail', exact: true }).count(), 0);
    record('Orbit drag does not accidentally select a room');
    await page.getByRole('button', { name: 'Atur ulang', exact: true }).click();
    await page.getByLabel('Atap', { exact: true }).check();
    const withRoof = await canvas.screenshot();
    await page.getByLabel('Atap', { exact: true }).uncheck();
    assert.notDeepEqual(await canvas.screenshot(), withRoof);
    await page.getByLabel('Atap', { exact: true }).check();
    const labeled = await canvas.screenshot();
    await page.getByLabel('Label', { exact: true }).uncheck();
    assert.notDeepEqual(await canvas.screenshot(), labeled);
    await page.getByLabel('Label', { exact: true }).check();
    const beforeZoom = await canvas.screenshot();
    await page.getByRole('button', { name: 'Perbesar peta', exact: true }).click();
    assert.notDeepEqual(await canvas.screenshot(), beforeZoom);
    await page.getByRole('button', { name: 'Atur ulang', exact: true }).click();
    record('Roof, label, zoom, reset controls change rendered canvas');
    await page.screenshot({ path: path.join(out, 'desktop.png'), fullPage: true });
    await canvas.screenshot({ path: path.join(out, 'map-3d.png') });
    await page.getByRole('button', { name: 'Bandingkan denah asli', exact: true }).click();
    await page.locator('img[alt^="Denah sumber"]').evaluate(img => img.decode());
    assert.equal(await top.isEnabled(), false);
    await page.getByRole('button', { name: 'Kembali ke 3D', exact: true }).click();
    assert.equal(await top.isEnabled(), true);
    record('Original floorplan comparison loads and returns to 3D');
    for (const width of [1024, 768, 390]) {
      await page.setViewportSize({ width, height: 900 });
      await page.getByRole('button', { name: 'Atur ulang', exact: true }).click();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth), width);
      await page.screenshot({ path: path.join(out, `viewport-${width}.png`), fullPage: true });
    }
    record('No horizontal document overflow at 1024, 768, or 390 pixels');
    await page.locator('#map-search').fill('gazebo');
    await list.getByRole('button').last().click();
    assert.equal(await page.getByRole('heading', { name: 'Gazebo kanan', exact: true }).count(), 1);
    record('Mobile search and room selection functional');
    await page.getByRole('button', { name: 'Hapus filter', exact: true }).click();
    await canvas.evaluate(el => { const gl = el.getContext('webgl2'); const ext = gl && gl.getExtension('WEBGL_lose_context'); if (!ext) throw new Error('Context loss test unsupported'); ext.loseContext(); });
    await page.getByText('Tampilan 3D tidak tersedia pada perangkat ini.', { exact: false }).waitFor();
    await list.getByRole('button').first().click();
    assert.equal(await page.getByRole('heading', { name: 'Panggung Aula Luar', exact: true }).count(), 1);
    record('WebGL context loss falls back to source plan and working directory');
    await page.screenshot({ path: path.join(out, 'webgl-fallback.png'), fullPage: true });
    await page.locator('main a[href="/"]').first().click();
    await page.getByRole('link', { name: 'Jelajahi peta sekolah', exact: false }).click();
    await page.locator('[data-testid="school-map-canvas"] canvas').waitFor();
    assert.equal(await page.locator('[data-testid="school-map-canvas"] canvas').count(), 1);
    await page.getByRole('button', { name: 'Tampak atas', exact: true }).click();
    record('Homepage CTA navigation remounts a single working renderer after leaving map');
    await page.goto(base + '/tentang/fasilitas');
    await page.getByRole('link', { name: 'Temukan fasilitas di peta 3D', exact: false }).click();
    await page.locator('[data-testid="school-map-canvas"] canvas').waitFor();
    record('Facilities page links to working map');
    assert.match(await (await page.request.get(base + '/sitemap.xml')).text(), /\/peta-sekolah<\/loc>/);
    record('Map route is present in real sitemap response');
    assert.deepEqual(errors, []);
    record('No uncaught browser JavaScript errors across map flows');
    fs.writeFileSync(path.join(out, 'browser-results.json'), JSON.stringify({ base, roomCount: total, checks, errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { fs.writeFileSync(path.join(out, 'browser-failure.json'), JSON.stringify({ checks, error: error.stack }, null, 2)); console.error(error); process.exit(1); });
